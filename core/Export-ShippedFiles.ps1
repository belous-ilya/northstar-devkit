#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Writes core/ShippedFiles.txt - the list of every file the installer puts
    under core\ and tools\. Re-run this after adding, renaming or deleting
    any file in either folder.
.DESCRIPTION
    core/Remove-StaleInstallFiles.ps1 (run by the installer after an update)
    deletes whatever is in those two folders and NOT on this list, which is
    how a script removed from the product also disappears from installs that
    update. The list therefore has to match the tree exactly:
    tests/Unit/ShippedFiles.Tests.ps1 fails when it does not, in either
    direction - a missing entry would get a shipped file deleted on update,
    an extra entry would let a removed one stay.

    Dev-time only, like Export-Catalog.ps1.
#>

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$outPath = Join-Path $PSScriptRoot 'ShippedFiles.txt'

$entries = New-Object 'System.Collections.Generic.List[string]'
foreach ($folder in 'core', 'tools') {
    $base = Join-Path $repoRoot $folder
    foreach ($file in (Get-ChildItem -LiteralPath $base -Recurse -File -Force)) {
        $entries.Add($file.FullName.Substring($repoRoot.Length + 1))
    }
}
# The list ships too, and has to name itself (it may not exist yet on a
# first run).
$self = 'core\ShippedFiles.txt'
if (-not ($entries -contains $self)) { $entries.Add($self) }

$sorted = @($entries | Sort-Object { $_.ToLowerInvariant() } -Unique)
$header = @(
    '# Every file the installer puts under core\ and tools\. GENERATED by'
    '# core/Export-ShippedFiles.ps1 - do not edit by hand. After an update,'
    '# core/Remove-StaleInstallFiles.ps1 deletes anything in those two folders'
    '# that is not listed here.'
)
[System.IO.File]::WriteAllLines($outPath, [string[]]($header + $sorted), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote $outPath - $($sorted.Count) files." -ForegroundColor Green
